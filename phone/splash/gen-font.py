#!/usr/bin/env python3
# gen-font.py — render ASCII 32..126 from a monospace TTF into an 8x16 bitmap
# C header for pryzent-splash. Run once; the generated font.h is committed.
#   python3 gen-font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf > font.h
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
font = ImageFont.truetype(sys.argv[1], 13)
print("/* Generated by gen-font.py from %s (DejaVu fonts license: free). */"
      % sys.argv[1].rsplit("/", 1)[-1])
print("#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 32\n#define FONT_LAST 126" % (W, H))
print("static const unsigned char font_bits[%d][%d] = {" % (126 - 32 + 1, H))
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), chr(c), font=font, fill=255)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) > 100:
                b |= 0x80 >> x
        rows.append("0x%02x" % b)
    print("    {%s}, /* %r */" % (",".join(rows), chr(c)))
print("};")
